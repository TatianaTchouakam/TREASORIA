@st.cache_data
def load_data_quality_status() -> dict:
    """
    Run compact integrity checks against
    the curated Treasoria dataset.
    """

    issues: list[str] = []
    dataset_path = _find_dataset_dir()

    if dataset_path is None:
        return {"available": False, "issues": [], "last_synced": None}

    gold_path = dataset_path / "gold"
    silver_path = dataset_path / "silver"

    last_synced = None
    kpi_file = gold_path / "gold_kpi_summary.csv"

    if kpi_file.exists():
        last_synced = datetime.fromtimestamp(
            kpi_file.stat().st_mtime, tz=ZoneInfo("Europe/Berlin")
        )

    # --------------------------------------------------------
    # CHECK 1: ACCOUNTING RECONCILIATION
    # --------------------------------------------------------

    try:
        kpi_df = pd.read_csv(kpi_file)
        kpi_map = dict(zip(kpi_df["kpi"], kpi_df["value"]))

        opening_raw = kpi_map.get(
            "Opening Cash Balance (two accounts)", ""
        )

        opening = (
            float(opening_raw.replace("EUR", "").replace(",", "").strip())
            if opening_raw else None
        )

        monthly = pd.read_csv(gold_path / "gold_monthly_cash_flow.csv")
        daily = pd.read_csv(gold_path / "gold_daily_cash_position.csv")

        net_total = monthly["net_cash_flow"].sum()
        ending = daily.iloc[-1]["consolidated_cash_balance"]

        if opening is not None and abs((opening + net_total) - ending) > 1.0:
            issues.append(
                "Accounting reconciliation mismatch "
                "(opening cash + net flow ≠ closing balance)"
            )

    except Exception:
        issues.append("Could not verify accounting reconciliation")

    # --------------------------------------------------------
    # CHECK 2: SUPPLIER INVOICE TRACEABILITY
    # --------------------------------------------------------

    try:
        supplier = pd.read_csv(silver_path / "fact_supplier_invoice.csv")
        orphan_count = int(supplier["source_transaction_id"].isna().sum())

        if orphan_count > 0:
            issues.append(
                f"{orphan_count} supplier invoice(s) "
                "with no linked bank transaction"
            )

    except Exception:
        pass

    # --------------------------------------------------------
    # CHECK 3: DUPLICATE MAIN TRANSACTION IDS
    # --------------------------------------------------------

    try:
        main = pd.read_csv(silver_path / "fact_checking_main.csv")
        duplicate_count = int(main["transaction_id"].duplicated().sum())

        if duplicate_count > 0:
            issues.append(
                f"{duplicate_count} duplicate transaction ID(s) detected"
            )

    except Exception:
        pass

    return {"available": True, "issues": issues, "last_synced": last_synced}


def render_data_quality_badge() -> None:
    """
    Display a compact trust signal on the Overview page.
    """

    status = load_data_quality_status()

    if not status["available"]:
        st.caption("○ Data quality check unavailable — dataset not found")
        return

    if status["issues"]:
        label = (
            "🟠 Data quality issue detected · "
            f"{len(status['issues'])} item(s) need review"
        )

        with st.popover(label):
            st.markdown("**Issues found:**")
            for issue in status["issues"]:
                st.markdown(f"- {issue}")

    else:
        synced = (
            status["last_synced"].strftime("%Y-%m-%d %H:%M")
            if status["last_synced"] else "unknown"
        )

        with st.popover(f"🟢 Data verified · last synced {synced}"):
            st.markdown("All integrity checks passed:")
            st.markdown("- Opening cash + net cash flow = closing balance ✓")
            st.markdown("- All supplier invoices linked to a source transaction ✓")
            st.markdown("- No duplicate transaction IDs ✓")


@st.cache_data
def load_overview_data() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Load the three Gold tables the Overview page's charts and
    signals are built from: monthly cash flow, daily cash position,
    and receivables aging.

    WHY this exists as one function: the chart_column/signal_column
    section and the Cash Outlook section both need the same three
    tables, loaded and parsed the same way (dates as real datetimes,
    not strings) -- centralising it here means both call sites stay
    in sync if the underlying file paths or column types ever change.
    """

    dataset_path = _find_dataset_dir()

    if dataset_path is None:
        raise FileNotFoundError("Treasoria dataset not found.")

    gold_path = dataset_path / "gold"

    monthly = pd.read_csv(gold_path / "gold_monthly_cash_flow.csv")
    daily = pd.read_csv(gold_path / "gold_daily_cash_position.csv")
    receivables = pd.read_csv(gold_path / "gold_receivables_aging.csv")

    monthly["month"] = pd.to_datetime(monthly["month"])
    daily["date"] = pd.to_datetime(daily["date"])

    return monthly, daily, receivables


