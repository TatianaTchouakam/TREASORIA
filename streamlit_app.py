def _find_dataset_dir() -> Path | None:
    """
    Locate the Treasoria structured dataset.
    """

    project_root = Path(__file__).parent
    data_path = project_root / "data"

    dataset_directories = [
        directory
        for directory in data_path.glob("Treasoria_Datasets*")
        if directory.is_dir()
    ]

    return dataset_directories[0] if dataset_directories else None


