def render_feedback(message_index: int) -> None:
    """
    Render thumbs-up / thumbs-down feedback.
    """

    key = f"feedback_{message_index}"
    current_vote = st.session_state.get(key)

    col_up, col_down, _ = st.columns([1, 1, 10])

    with col_up:
        if st.button(
            "👍",
            key=f"{key}_up",
            type="primary" if current_vote == "up" else "secondary",
        ):
            st.session_state[key] = None if current_vote == "up" else "up"
            st.rerun()

    with col_down:
        if st.button(
            "👎",
            key=f"{key}_down",
            type="primary" if current_vote == "down" else "secondary",
        ):
            st.session_state[key] = None if current_vote == "down" else "down"
            st.rerun()


