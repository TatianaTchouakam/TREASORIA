@st.cache_data
def load_kpi_summary() -> dict[str, str]:
    """
    Load the KPI summary generated by the Gold layer.
    """

    dataset_path = (
        _find_dataset_dir()
    )

    if dataset_path is None:

        raise FileNotFoundError(
            "The Treasoria dataset directory "
            "was not found inside data/."
        )

    kpi_file_path = (
        dataset_path
        / "gold"
        / "gold_kpi_summary.csv"
    )

    if not kpi_file_path.exists():

        raise FileNotFoundError(
            f"KPI file not found: "
            f"{kpi_file_path}"
        )

    kpi_dataframe = pd.read_csv(
        kpi_file_path
    )

    if not {
        "kpi",
        "value",
    }.issubset(
        kpi_dataframe.columns
    ):

        raise ValueError(
            "The KPI file must contain "
            "the columns 'kpi' and 'value'."
        )

    kpi_dataframe = (
        kpi_dataframe
        .dropna(
            subset=[
                "kpi",
                "value",
            ]
        )
    )

    return {
        str(row["kpi"]).strip():
            str(row["value"]).strip()
        for _, row
        in kpi_dataframe.iterrows()
    }


