def _now_berlin() -> str:
    """
    Return the current local time for Bielefeld.
    """

    return datetime.now(
        ZoneInfo("Europe/Berlin")
    ).strftime(
        "%Y-%m-%d %H:%M"
    )


def load_company() -> dict:
    """
    Load the saved company profile.
    """

    profile = DEFAULT_COMPANY.copy()

    if COMPANY_PROFILE_PATH.exists():

        with open(
            COMPANY_PROFILE_PATH,
            "r",
            encoding="utf-8",
        ) as file:

            saved = json.load(file)

        profile.update(saved)

    return profile


def save_company(
    profile: dict,
) -> None:
    """
    Save the active company profile.
    """

    profile["last_updated"] = (
        _now_berlin()
    )

    COMPANY_PROFILE_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with open(
        COMPANY_PROFILE_PATH,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            profile,
            file,
            ensure_ascii=False,
            indent=2,
        )


